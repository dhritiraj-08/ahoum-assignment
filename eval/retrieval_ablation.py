"""
eval/retrieval_ablation.py
---------------------------
Ablation study answering a question `docs/DECISIONS.md` #1 and
`docs/DEBUGGING.md` #1 raised but never actually tested: does the TEXT we
embed per facet change FAISS retrieval recall, independent of top_k?

Widening top_k from 25 to 40 (see DECISIONS.md #1) only recovered 1 of 13
retrieval misses, which pointed at the embedding text itself -- the
generic templated scoring-anchor sentences don't read like natural
conversation -- as the real bottleneck, not the retrieval window. This
script tests that hypothesis directly instead of just asserting it: build
4 small temporary FAISS indexes over the exact same 316 observable facets,
one per embedding-text format, and measure recall against the exact same
10 benchmark conversations and 27 retrievable reference facets
`src/benchmark.py` already uses. Same top_k for all 4 (25, matching what
this ablation was asked to test at) so the ONLY variable is the text.

No LLM calls anywhere in this script -- pure FAISS/sentence-transformers
retrieval, same as src/embeddings.py, just with 4 different text formats
instead of 1. Run with:

    python eval/retrieval_ablation.py
"""

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import pandas as pd

try:
    import faiss
except ImportError as e:
    raise ImportError("faiss-cpu is not installed. Run: pip install -r requirements.txt") from e

try:
    from sentence_transformers import SentenceTransformer
except ImportError as e:
    raise ImportError("sentence-transformers is not installed. Run: pip install -r requirements.txt") from e

from src.benchmark import BENCHMARK_CASES
from src import embeddings as embeddings_module

ENRICHED_CSV_PATH = PROJECT_ROOT / "outputs" / "enriched_facets.csv"
REPORT_PATH = PROJECT_ROOT / "outputs" / "retrieval_ablation_report.md"
EMBEDDING_MODEL_NAME = "all-MiniLM-L6-v2"
TOP_K = 25

_model = None


def _get_model() -> "SentenceTransformer":
    global _model
    if _model is None:
        _model = SentenceTransformer(EMBEDDING_MODEL_NAME)
    return _model


def _build_example_phrasings(facet_name: str) -> str:
    """
    Two short example phrasings per facet, generated by a plain string
    template keyed only on the facet's own name -- NOT an LLM call, and
    deliberately mechanical rather than hand-tuned per facet. The point of
    approach 4 isn't "how good can example phrasing get with real effort,"
    it's "does even this crude a level of naturalistic-sounding text help
    retrieval at all" -- a cheap, reproducible experiment.
    """
    name_lower = (facet_name[0].lower() + facet_name[1:]) if facet_name else facet_name
    example_high = (
        f"For example, someone high in {name_lower} would show this clearly "
        f"through what they say and do."
    )
    example_low = (
        f"Someone low in {name_lower}, or showing the opposite, would say or "
        f"do things reflecting little to none of it."
    )
    return f"{example_high} {example_low}"


def _build_text_bare_name(row: dict) -> str:
    return row["facet_normalized"]


def _build_text_name_plus_category(row: dict) -> str:
    return f"{row['facet_normalized']} ({row['category']})"


def _build_text_name_plus_anchors(row: dict) -> str:
    # This is exactly src/embeddings.py's build_index() format -- the
    # current, real implementation -- included here as the baseline every
    # other approach is measured against.
    return f"{row['facet_normalized']}: {row['scoring_anchors']}"


def _build_text_name_plus_anchors_plus_examples(row: dict) -> str:
    base = f"{row['facet_normalized']}: {row['scoring_anchors']}"
    return f"{base} {_build_example_phrasings(row['facet_normalized'])}"


APPROACHES = [
    {
        "key": "bare_name",
        "label": "1. Bare facet name only",
        "build_text": _build_text_bare_name,
    },
    {
        "key": "name_plus_category",
        "label": "2. Facet name + category",
        "build_text": _build_text_name_plus_category,
    },
    {
        "key": "name_plus_anchors",
        "label": "3. Facet name + scoring anchors (current implementation)",
        "build_text": _build_text_name_plus_anchors,
    },
    {
        "key": "name_plus_anchors_plus_examples",
        "label": "4. Facet name + scoring anchors + 2 template example phrasings",
        "build_text": _build_text_name_plus_anchors_plus_examples,
    },
]


def _load_observable_df() -> pd.DataFrame:
    if not ENRICHED_CSV_PATH.exists():
        raise FileNotFoundError(f"{ENRICHED_CSV_PATH} not found. Run `python main.py --audit` first.")
    df = pd.read_csv(ENRICHED_CSV_PATH).fillna("")
    observable = df[df["conversation_observable"] == True].reset_index(drop=True)  # noqa: E712
    if observable.empty:
        raise ValueError("No conversation-observable facets found in enriched_facets.csv.")
    return observable


def _build_index_for_approach(df: pd.DataFrame, build_text) -> tuple:
    texts = [build_text(row) for row in df.to_dict(orient="records")]
    model = _get_model()
    vectors = model.encode(texts, convert_to_numpy=True, normalize_embeddings=True, show_progress_bar=False)
    vectors = np.asarray(vectors, dtype="float32")
    index = faiss.IndexFlatIP(vectors.shape[1])
    index.add(vectors)
    meta = df.to_dict(orient="records")
    return index, meta


def _retrieve_names(index, meta: list, model, conversation: str, top_k: int) -> set:
    query_vec = model.encode([conversation], convert_to_numpy=True, normalize_embeddings=True)
    query_vec = np.asarray(query_vec, dtype="float32")
    k = max(1, min(top_k, index.ntotal))
    _, indices = index.search(query_vec, k)
    names = set()
    for idx in indices[0]:
        if 0 <= idx < len(meta):
            names.add(meta[idx]["facet_normalized"])
    return names


def _retrievable_reference_items() -> list:
    """
    Same criterion src/benchmark.py's force-include mechanism uses: only
    reference facets that are supposed to be genuinely observable
    (expected_status "scored" or "insufficient_evidence") count. The
    medical/spiritual "not_observable" trap facets are excluded from this
    ablation entirely -- they're structurally absent from the observable
    corpus this script indexes, same as in production, so there's nothing
    to measure retrieval of for them.
    """
    items = []
    for case in BENCHMARK_CASES:
        for ref in case["reference"]:
            if ref["expected_status"] != "not_observable":
                items.append({"conversation_id": case["id"], "conversation_type": case["type"], "facet": ref["facet"]})
    return items


def run_ablation(k_values: list = None) -> dict:
    """
    Runs all 4 approaches at every k in k_values (default [10, 25, 40, 100]
    -- chosen to bracket the actual top_k values used elsewhere in this
    project: 10 is below any real usage, 25 was the original pipeline
    default, 40 is the current one, 100 is well above anything used today,
    to see whether a wider window changes which approach wins). Each
    approach's index is built exactly once and reused across all k values
    -- index construction doesn't depend on k, only the search step does,
    so this avoids rebuilding 4 indexes 4 times over for no reason.
    """
    if k_values is None:
        k_values = [10, 25, 40, 100]

    df = _load_observable_df()
    model = _get_model()
    retrievable_items = _retrievable_reference_items()
    total_retrievable = len(retrievable_items)

    print(f"Observable facets indexed per approach: {len(df)}")
    print(f"Retrievable reference facets being measured: {total_retrievable}")
    print(f"k values: {k_values}\n")

    # results[approach_key][k] = {naturally_retrieved, recall, misses}
    results: dict = {}
    for approach in APPROACHES:
        print(f"Building index -- {approach['label']} ...")
        index, meta = _build_index_for_approach(df, approach["build_text"])

        per_k = {}
        for k in k_values:
            naturally_retrieved = 0
            misses = []
            for case in BENCHMARK_CASES:
                retrieved_names = _retrieve_names(index, meta, model, case["conversation"], k)
                for ref in case["reference"]:
                    if ref["expected_status"] == "not_observable":
                        continue
                    if ref["facet"] in retrieved_names:
                        naturally_retrieved += 1
                    else:
                        misses.append({"conversation_id": case["id"], "conversation_type": case["type"], "facet": ref["facet"]})

            recall = naturally_retrieved / total_retrievable if total_retrievable else 0.0
            per_k[k] = {
                "naturally_retrieved": naturally_retrieved,
                "total_retrievable": total_retrievable,
                "recall": recall,
                "misses": misses,
            }
            print(f"  k={k:<4} recall: {recall * 100:.0f}%  ({naturally_retrieved}/{total_retrievable})")

        results[approach["key"]] = {"label": approach["label"], "per_k": per_k}
        print()

    # Approach 5: BM25 hybrid (FAISS + BM25 via RRF). Unlike approaches 1-4,
    # this doesn't build its own ablation-local index -- it calls the REAL
    # production src.embeddings.retrieve_hybrid() against the real indexes
    # on disk (outputs/faiss_index.bin + outputs/bm25_index.pkl, built by
    # `python main.py --embed`), using the exact same "name + scoring
    # anchors" text as approach 3 (that's what build_index() actually
    # embeds). This measures what's actually shipped, not a re-derived
    # approximation of it, at the cost of requiring --embed to have been
    # run with the current src/embeddings.py first.
    print("Measuring -- 5. BM25 hybrid (FAISS + BM25 via RRF, production retrieve_hybrid()) ...")
    hybrid_per_k = {}
    try:
        for k in k_values:
            naturally_retrieved = 0
            misses = []
            for case in BENCHMARK_CASES:
                retrieved = embeddings_module.retrieve_hybrid(case["conversation"], top_k=k)
                retrieved_names = {f["facet_normalized"] for f in retrieved}
                for ref in case["reference"]:
                    if ref["expected_status"] == "not_observable":
                        continue
                    if ref["facet"] in retrieved_names:
                        naturally_retrieved += 1
                    else:
                        misses.append({"conversation_id": case["id"], "conversation_type": case["type"], "facet": ref["facet"]})

            recall = naturally_retrieved / total_retrievable if total_retrievable else 0.0
            hybrid_per_k[k] = {
                "naturally_retrieved": naturally_retrieved,
                "total_retrievable": total_retrievable,
                "recall": recall,
                "misses": misses,
            }
            print(f"  k={k:<4} recall: {recall * 100:.0f}%  ({naturally_retrieved}/{total_retrievable})")
        results["bm25_hybrid"] = {"label": "5. BM25 hybrid (FAISS + BM25, RRF)", "per_k": hybrid_per_k}
    except FileNotFoundError as e:
        print(f"  SKIPPED -- {e}")
    print()

    _write_report(results, k_values, total_retrievable, len(df))
    print(f"Saved report to {REPORT_PATH}")
    return results


def _write_report(results: dict, k_values: list, total_retrievable: int, n_facets_indexed: int) -> None:
    ordered_keys = [a["key"] for a in APPROACHES if a["key"] in results]
    has_hybrid = "bm25_hybrid" in results
    if has_hybrid:
        ordered_keys = ordered_keys + ["bm25_hybrid"]
    baseline_key = "name_plus_anchors"
    detail_k = 25 if 25 in k_values else k_values[len(k_values) // 2]  # k to show detailed misses for

    lines = []
    lines.append("# Retrieval Ablation: Does Embedding Text Format Change Recall?")
    lines.append("")
    approach_count = len(ordered_keys)
    lines.append(
        f"Tests {approach_count} retrieval approaches for the same "
        f"**{n_facets_indexed}** conversation-observable facets, at "
        f"**k in {k_values}**, against the same 10 benchmark conversations "
        f"`src/benchmark.py` uses, measured against the same "
        f"**{total_retrievable}** retrievable reference facets its "
        "force-include mechanism tracks. Approaches 1-4 are pure "
        "FAISS/sentence-transformers retrieval (no LLM calls), each with a "
        "different embedding-text format. Approach 5, if present, is the "
        "real production `retrieve_hybrid()` -- FAISS + BM25 combined via "
        "Reciprocal Rank Fusion -- measured against the actual indexes on "
        "disk, not a re-derived approximation."
    )
    lines.append("")
    lines.append(
        "**Why this exists:** `docs/DECISIONS.md` #1 and `docs/DEBUGGING.md` "
        "#1 both concluded that embedding-text quality, not `top_k`, is the "
        "root cause of retrieval misses -- widening `top_k` from 25 to 40 "
        "only recovered 1 of 13 misses. That conclusion was inferred, never "
        "directly tested. This script tests it, and now tests it across "
        "multiple k values (10/25/40/100) rather than just one, so a claim "
        "like \"approach 3 wins\" can say at *which* k, or all of them."
    )
    lines.append("")
    lines.append("## Results: recall by approach x k")
    lines.append("")
    header = "| Approach | " + " | ".join(f"k={k}" for k in k_values) + " |"
    sep = "|---|" + "|".join(["---"] * len(k_values)) + "|"
    lines.append(header)
    lines.append(sep)

    wins_per_k = {k: max(ordered_keys, key=lambda key: results[key]["per_k"][k]["recall"]) for k in k_values}
    for key in ordered_keys:
        row_cells = []
        for k in k_values:
            r = results[key]["per_k"][k]
            marker = " 🏆" if wins_per_k[k] == key else ""
            row_cells.append(f"{r['recall'] * 100:.0f}%{marker}")
        lines.append(f"| {results[key]['label']} | " + " | ".join(row_cells) + " |")
    lines.append("")

    approach3_wins_all_k = all(wins_per_k[k] == baseline_key for k in k_values)

    lines.append("## Reading the result")
    lines.append("")
    if approach3_wins_all_k:
        lines.append(
            f"**Approach 3 (current implementation) wins at every k tested "
            f"({', '.join(str(k) for k in k_values)})** -- none of the "
            "alternative text formats beat it at any candidate-window size. "
            "That's a real, useful negative result, and a stronger one than "
            "a single-k test could give: it means the retrieval-miss problem "
            "documented in `DECISIONS.md` #1 isn't fixed by simply changing "
            "what generic text gets embedded alongside the facet name, "
            "regardless of how wide the retrieval window is. In particular, "
            "**approach 4 (name + anchors + template example phrasings) "
            "scored WORSE than approach 3 at every k** -- the hypothesis "
            "that adding example phrasings would help was wrong, not just "
            "unproven; see `DEBUGGING.md` #5 for the root cause. The fix, if "
            "there is one at this embedding-model scale, likely needs "
            "example text generated from real conversational phrasing "
            "rather than a template, or a fundamentally different retrieval "
            "strategy (a cross-encoder reranker, per `README.md`)."
        )
    else:
        winners = {k: results[wins_per_k[k]]["label"] for k in k_values}
        lines.append(
            "The winning approach isn't consistent across every k tested -- "
            + "; ".join(f"at k={k}, **{winners[k]}** wins" for k in k_values)
            + ". That itself is worth knowing: it means the choice of "
            "embedding text format and the choice of retrieval window "
            "interact, rather than one strictly dominating regardless of "
            "the other."
        )
    lines.append("")

    if has_hybrid:
        lines.append("## BM25 hybrid vs. baseline (approach 3), directly")
        lines.append("")
        for k in k_values:
            baseline_recall = results[baseline_key]["per_k"][k]["recall"] * 100
            hybrid_recall = results["bm25_hybrid"]["per_k"][k]["recall"] * 100
            delta = hybrid_recall - baseline_recall
            direction = "better" if delta > 0 else ("worse" if delta < 0 else "unchanged")
            lines.append(
                f"- k={k}: baseline {baseline_recall:.0f}% -> hybrid "
                f"{hybrid_recall:.0f}% ({delta:+.0f} points, {direction})"
            )
        lines.append("")

    lines.append(f"## Per-approach misses at k={detail_k}")
    lines.append("")
    lines.append(
        f"Detailed miss list at k={detail_k} only (to keep this readable -- "
        f"the summary table above already covers all {len(k_values)} k "
        "values). Useful for spotting whether the SAME facets keep missing "
        "across every approach (a harder retrieval problem) or whether "
        "different approaches miss different facets (more sensitive to "
        "phrasing)."
    )
    lines.append("")
    for key in ordered_keys:
        r = results[key]["per_k"][detail_k]
        lines.append(f"**{results[key]['label']}** -- {len(r['misses'])} miss(es):")
        if not r["misses"]:
            lines.append("- _none_")
        else:
            for m in r["misses"]:
                lines.append(f"- `{m['facet']}` (conversation {m['conversation_id']}: {m['conversation_type']})")
        lines.append("")

    miss_sets = [set(m["facet"] for m in results[key]["per_k"][detail_k]["misses"]) for key in ordered_keys]
    always_missed = set.intersection(*miss_sets) if miss_sets else set()
    lines.append(f"## Facets that missed under every approach (at k={detail_k})")
    lines.append("")
    if always_missed:
        lines.append(
            "These missed regardless of embedding text format -- changing "
            "*what* gets embedded won't fix these; they need a different "
            "retrieval strategy entirely (wider top_k, a reranker, or "
            "hybrid keyword+embedding search):"
        )
        lines.append("")
        for facet in sorted(always_missed):
            lines.append(f"- `{facet}`")
    else:
        lines.append("None -- every reference facet was retrieved by at least one approach.")
    lines.append("")

    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    run_ablation()
